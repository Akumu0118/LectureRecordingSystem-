from datetime import datetime
from typing import Annotated
from uuid import UUID

from pydantic import AfterValidator, AwareDatetime, BaseModel, ConfigDict, StringConstraints, field_validator, model_validator

from app.models import RecordingStatus
from app.schemas.lecturer import LecturerRead, no_controls
from app.schemas.voice_sample import ReferenceAudioRead

Title = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=250), AfterValidator(no_controls)]
Description = Annotated[str, StringConstraints(strip_whitespace=True, max_length=10000)]


class RecordingCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    id: UUID | None = None  # Optional retry identifier, generated by the browser.
    lecturer_id: UUID
    title: Title
    description: Description | None = None
    recorded_at: AwareDatetime | None = None

    @field_validator("description")
    @classmethod
    def description_valid(cls, value):
        if value is not None and "\x00" in value:
            raise ValueError("Description cannot contain NUL characters")
        return value or None


class RecordingUpdate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    title: Title | None = None
    description: Description | None = None

    @field_validator("title")
    @classmethod
    def title_required(cls, value):
        if value is None:
            raise ValueError("Title cannot be null")
        return value

    @field_validator("description")
    @classmethod
    def description_valid(cls, value):
        return RecordingCreate.description_valid(value)

    @model_validator(mode="after")
    def require_change(self):
        if not self.model_fields_set:
            raise ValueError("Provide title or description")
        return self


class RecordingRead(BaseModel):
    id: UUID
    lecturer_id: UUID
    lecturer: LecturerRead
    title: str
    description: str | None
    status: RecordingStatus
    recorded_at: datetime | None
    created_at: datetime
    updated_at: datetime
    original_audio: ReferenceAudioRead | None
    audio_url: str | None


class RecordingPage(BaseModel):
    items: list[RecordingRead]
    total: int
    limit: int
    offset: int


class RecordingDeleted(BaseModel):
    id: UUID
    deleted: bool = True
    file_cleanup_pending: bool = False
